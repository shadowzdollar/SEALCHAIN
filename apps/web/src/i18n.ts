export const DICTS: Record<Lang, Dict> = { en, fr, sw, rw };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('sc-lang');
    if (saved && saved in DICTS) return saved as Lang;
  } catch {
    /* storage unavailable */
  }
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = l.toLowerCase().slice(0, 2);
    if (base === 'fr' || base === 'sw' || base === 'rw') return base;
  }
  return 'en';
}

type Key = Exclude<keyof Dict, 'status'>;
export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: 'en', setLang: () => {} });

export function useT() {
  const { lang } = useContext(LangContext);
  const d = DICTS[lang];
  const t = (key: Key, vars: Record<string, string | number> = {}) =>
    (d[key] as string).replace(/\{(\w+)\}/g, (_, v: string) => String(vars[v] ?? ''));
  return { t, lang, status: (s: string) => d.status[s] ?? s };
}
