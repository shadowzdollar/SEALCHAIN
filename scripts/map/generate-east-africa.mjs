#!/usr/bin/env node
/**
 * Generates apps/web/src/marketing/eastAfricaMap.ts — the corridor map's
 * geography, pre-projected to SVG paths so the site ships no map library.
 *
 * Data: Natural Earth 1:50m admin-0 countries (via world-atlas) and lakes —
 * public domain (naturalearthdata.com).
 *
 * Run from a folder where the two data files and the tools are available:
 *   npm i d3-geo topojson-client
 *   curl -LO https://cdn.jsdelivr.net/npm/world-atlas@2/countries-50m.json
 *   curl -L -o lakes-50m.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_lakes.geojson
 *   node generate-east-africa.mjs <repo>/apps/web/src/marketing/eastAfricaMap.ts
 */
import fs from 'node:fs';
import { geoMercator, geoPath, geoBounds } from 'd3-geo';
import { feature } from 'topojson-client';

const OUT = process.argv[2];
if (!OUT) throw new Error('usage: node generate-east-africa.mjs <output.ts>');

const W = 800;
const H = 700;
// Western Rwanda/Burundi to the Kenyan coast, Uganda's north to southern Tanzania.
const EXTENT = { type: 'Feature', geometry: { type: 'Polygon', coordinates: [[[27.6, 3.6], [42.2, 3.6], [42.2, -9.2], [27.6, -9.2], [27.6, 3.6]]] } };
const projection = geoMercator().fitExtent([[0, 0], [W, H]], EXTENT);
const path = geoPath(projection);
if (path.digits) path.digits(1);
const pt = ([lon, lat]) => projection([lon, lat]).map((v) => Math.round(v * 10) / 10);

const topo = JSON.parse(fs.readFileSync('countries-50m.json', 'utf8'));
const countries = feature(topo, topo.objects.countries).features;

// ISO 3166 numeric → code; EAC corridor countries are drawn as "served".
const WANTED = {
  646: ['RW', 'Rwanda', true], 108: ['BI', 'Burundi', true], 800: ['UG', 'Uganda', true], 404: ['KE', 'Kenya', true], 834: ['TZ', 'Tanzania', true],
  180: ['CD', 'DR Congo', false], 728: ['SS', 'South Sudan', false], 231: ['ET', 'Ethiopia', false], 706: ['SO', 'Somalia', false],
  894: ['ZM', 'Zambia', false], 454: ['MW', 'Malawi', false], 508: ['MZ', 'Mozambique', false],
};
// Hand-placed label anchors [lon, lat] where the centroid reads poorly.
const LABEL_AT = { RW: [30.0, -1.6], BI: [29.9, -3.2], UG: [32.4, 1.6], KE: [37.9, 0.6], TZ: [34.6, -6.2], CD: [28.3, -2.6], SS: [31.6, 3.4], ET: [39.4, 3.3], SO: [41.6, 1.2], ZM: [30.6, -8.9], MW: [33.9, -9.0], MZ: [39.8, -9.0] };

const outCountries = countries
  .filter((f) => WANTED[Number(f.id)])
  .map((f) => {
    const [code, name, eac] = WANTED[Number(f.id)];
    return { code, name, eac, d: path(f), label: pt(LABEL_AT[code]) };
  })
  .filter((c) => c.d);

const lakesGeo = JSON.parse(fs.readFileSync('lakes-50m.geojson', 'utf8')).features;
const inExtent = (f) => {
  const [[x0, y0], [x1, y1]] = geoBounds(f);
  return x1 > 27.6 && x0 < 42.2 && y1 > -9.2 && y0 < 3.6;
};
const LAKE_LABEL = { 'Lake Victoria': [33.0, -1.1], 'Lake Tanganyika': [29.75, -6.2] };
const outLakes = lakesGeo.filter(inExtent).map((f) => {
  const name = f.properties.name || f.properties.name_en || '';
  return { name, d: path(f), label: LAKE_LABEL[name] ? pt(LAKE_LABEL[name]) : null };
}).filter((l) => l.d && l.d.length > 20);

// Places [lon, lat].
const PLACES = {
  kigali: ['Kigali', [30.0619, -1.9441]],
  kampala: ['Kampala', [32.5825, 0.3476]],
  nairobi: ['Nairobi', [36.8219, -1.2921]],
  mombasa: ['Mombasa', [39.6682, -4.0435]],
  dar: ['Dar es Salaam', [39.2083, -6.7924]],
  bujumbura: ['Bujumbura', [29.3599, -3.3614]],
};
const POSTS = {
  gatuna: ['Gatuna', [30.012, -1.428]],
  kagitumba: ['Kagitumba', [30.46, -1.05]],
  malaba: ['Malaba', [34.2817, 0.6376]],
  rusumo: ['Rusumo', [30.7833, -2.3833]],
  akanyaru: ['Akanyaru-Haut', [29.78, -2.78]],
};
// Indicative road routes through real towns.
const ROUTES = {
  'RW-UG': [[30.0619, -1.9441], [30.012, -1.428], [29.9899, -1.2486], [30.6545, -0.6072], [31.7341, -0.3338], [32.5825, 0.3476]],
  'RW-KE': [[30.0619, -1.9441], [30.012, -1.428], [29.9899, -1.2486], [30.6545, -0.6072], [31.7341, -0.3338], [32.5825, 0.3476], [33.2042, 0.4244], [34.2817, 0.6376], [35.2698, 0.5143], [36.08, -0.3031], [36.8219, -1.2921], [38.17, -2.69], [38.5561, -3.3961], [39.6682, -4.0435]],
  'RW-TZ': [[30.0619, -1.9441], [30.7833, -2.3833], [31.23, -3.01], [32.6, -3.8375], [33.18, -4.21], [34.7437, -4.8163], [35.7516, -6.163], [37.6591, -6.8278], [39.2083, -6.7924]],
  'RW-BI': [[30.0619, -1.9441], [29.7394, -2.5967], [29.78, -2.78], [29.63, -2.92], [29.3599, -3.3614]],
};

const project = (o) => Object.fromEntries(Object.entries(o).map(([k, [name, ll]]) => [k, { name, at: pt(ll) }]));
const routes = Object.fromEntries(Object.entries(ROUTES).map(([id, lls]) => [id, 'M' + lls.map((ll) => pt(ll).join(',')).join(' L')]));

const ts = `/**
 * East Africa corridor map — GENERATED by scripts/map/generate-east-africa.mjs.
 * Geography: Natural Earth 1:50m countries and lakes (public domain).
 * Mercator projection, ${W}×${H}. Routes are indicative road corridors.
 */
export const MAP = ${JSON.stringify({ width: W, height: H, countries: outCountries, lakes: outLakes, places: project(PLACES), posts: project(POSTS), routes }, null, 0)} as const;
`;
fs.writeFileSync(OUT, ts);
console.log(`wrote ${OUT}: ${outCountries.length} countries, ${outLakes.length} lakes, ${(ts.length / 1024).toFixed(1)} KB`);
